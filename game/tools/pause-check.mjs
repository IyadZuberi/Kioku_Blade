// The pause menu in a real browser: Esc opens it and freezes the fight, Resume carries on, forfeit goes to the title and counts as a defeat.
import { chromium } from "playwright";
const b = await chromium.launch({ channel: "chrome", headless: true, args: ["--use-angle=d3d11", "--use-gl=angle", "--enable-gpu", "--ignore-gpu-blocklist", "--mute-audio"] });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
p.on("pageerror", (e) => errs.push(e.message));
await p.goto((process.env.PERF_URL ?? "http://localhost:5410/") + "?boss=1&name=PauseCheck", { waitUntil: "load" });
await p.waitForFunction(() => window.__duel && window.__duel.ready, null, { timeout: 90000 });
await p.evaluate(() => { localStorage.removeItem("kioku.brain.PauseCheck.1"); window.__duel.game.startFight(); });
await p.waitForTimeout(1500);
let ok = true;
const check = (name, v, d = "") => { if (!v) ok = false; console.log(v ? "PASS" : "FAIL", name, d); };
check("pause chip visible in a duel", await p.evaluate(() => document.getElementById("pausechip")?.classList.contains("on")) || (await p.waitForTimeout(400), await p.evaluate(() => document.getElementById("pausechip")?.classList.contains("on"))));
await p.keyboard.press("Escape");
await p.waitForTimeout(300);
check("Esc opens the pause menu", await p.evaluate(() => document.getElementById("pause").classList.contains("on")));
const t0 = await p.evaluate(() => window.__duel.game.gameTime);
await p.waitForTimeout(1200);
const t1 = await p.evaluate(() => window.__duel.game.gameTime);
check("the fight is frozen while paused", Math.abs(t1 - t0) < 0.01, `${t0.toFixed(2)} -> ${t1.toFixed(2)}`);
check("menu has volumes, mode switch and leave", await p.evaluate(() => document.querySelectorAll("#pause input[type=range]").length === 4 && /Keyboard and mouse/.test(document.getElementById("pause").textContent) && /forfeits/.test(document.getElementById("pause").textContent)));
await p.screenshot({ path: `${process.env.TEMP}/pause_menu.png` });
await p.keyboard.press("Escape");
await p.waitForTimeout(1000);
const t2 = await p.evaluate(() => window.__duel.game.gameTime);
check("Esc resumes and time runs again", t2 > t1 + 0.3 && !(await p.evaluate(() => document.getElementById("pause").classList.contains("on"))), `${t1.toFixed(2)} -> ${t2.toFixed(2)}`);
await p.keyboard.press("Escape");
await p.waitForTimeout(300);
const leave = p.locator("#pause button.danger");
await leave.click();
check("first click asks to confirm", /Really leave/.test(await leave.textContent()));
await leave.click();
await p.waitForTimeout(800);
check("forfeit goes to the title", (await p.evaluate(() => window.__duel.game.state)) === "title");
const brain = await p.evaluate(() => JSON.parse(localStorage.getItem("kioku.brain.PauseCheck.1") ?? "null"));
check("the forfeit counts as a defeat he learns from", brain && brain.duels === 1 && brain.wins === 0, JSON.stringify(brain && { duels: brain.duels, wins: brain.wins, level: brain.level }));
check("no page errors", errs.length === 0, errs.slice(0, 2).join(" | "));
await b.close();
process.exit(ok ? 0 : 1);
