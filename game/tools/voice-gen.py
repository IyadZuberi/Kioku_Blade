"""
Voice-over for every story line, made offline with Piper TTS (public-domain / CC0 voices), then darkened:
the generals are pitched down and given a short hall reverb so they sound older and heavier.

  1. ../server/node_modules/.bin/tsx tools/story-lines.ts > lines.json
  2. python tools/voice-gen.py lines.json <voices dir> public/assets/voice
     (voices: rhasspy/piper-voices on Hugging Face: en_US-norman-medium, en_US-john-medium,
      en_US-bryce-medium, en_US-joe-medium, en_GB-cori-high)
Writes <id>.mp3 per line and src/audio/voiceLines.ts (the set of voiced ids).
"""
import json, sys, os, wave, io
import numpy as np
import soundfile as sf
from piper import PiperVoice, SynthesisConfig

lines_path, voices_dir, out_dir = sys.argv[1], sys.argv[2], sys.argv[3]
os.makedirs(out_dir, exist_ok=True)

# speaker -> (voice file, pitch factor (<1 = deeper), length scale (>1 = slower), reverb mix)
CAST = {
    "narrator": ("en_US-norman-medium", 0.93, 1.12, 0.10),
    "kaede": ("en_GB-cori-high", 1.0, 1.0, 0.05),
    "masatora": ("en_US-john-medium", 0.84, 1.1, 0.16),
    "kazemaru": ("en_US-joe-medium", 0.9, 0.98, 0.12),
    "kurogane": ("en_US-bryce-medium", 0.78, 1.16, 0.22),
}

voices = {}
def voice(name):
    if name not in voices:
        voices[name] = PiperVoice.load(os.path.join(voices_dir, name + ".onnx"))
    return voices[name]

def synth(text, name, length):
    v = voice(name)
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        v.synthesize_wav(text, w, syn_config=SynthesisConfig(length_scale=length, noise_scale=0.6, noise_w_scale=0.7))
    buf.seek(0)
    with wave.open(buf, "rb") as w:
        sr = w.getframerate()
        x = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768.0
    return x, sr

def pitch(x, f):
    """Resample so it plays back at factor f of the pitch (and 1/f the speed)."""
    if abs(f - 1) < 1e-3:
        return x
    n = int(len(x) / f)
    return np.interp(np.linspace(0, len(x) - 1, n), np.arange(len(x)), x).astype(np.float32)

def reverb(x, sr, mix):
    if mix <= 0:
        return x
    y = np.copy(x)
    for d, g in [(0.029, 0.5), (0.041, 0.42), (0.057, 0.35), (0.079, 0.28), (0.113, 0.2), (0.151, 0.14)]:
        k = int(d * sr)
        y[k:] += x[:-k] * g * mix * 2.2
    return y

manifest = []
for line in json.load(open(lines_path, encoding="utf8")):
    name, f, length, mix = CAST[line["who"]]
    x, sr = synth(line["text"], name, length)
    x = reverb(pitch(x, f), sr, mix)
    x = np.concatenate([np.zeros(int(0.08 * sr), np.float32), x, np.zeros(int(0.2 * sr), np.float32)])
    x = 0.89 * x / max(1e-6, np.abs(x).max())
    sf.write(os.path.join(out_dir, line["id"] + ".mp3"), x, sr, format="MP3")
    manifest.append(line["id"])
    print(line["id"], line["who"], f"{len(x) / sr:.1f}s")

ts = os.path.join(os.path.dirname(__file__), "..", "src", "audio", "voiceLines.ts")
with open(ts, "w", encoding="utf8") as o:
    o.write("// Generated by tools/voice-gen.py: the story lines that have a recorded voice in public/assets/voice.\n")
    o.write("export const VOICED: ReadonlySet<string> = new Set<string>([" + ", ".join(json.dumps(i) for i in manifest) + "]);\n")
